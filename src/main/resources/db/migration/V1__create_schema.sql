
CREATE TABLE customers (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(120) NOT NULL,
    cpf        VARCHAR(11)  NOT NULL,
    created_at TIMESTAMPTZ  NOT NULL,
    CONSTRAINT uq_customers_cpf UNIQUE (cpf),
    CONSTRAINT ck_customers_cpf CHECK (cpf ~ '^[0-9]{11}$')
);

CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(160) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    customer_id   BIGINT       NOT NULL,
    created_at    TIMESTAMPTZ  NOT NULL,
    CONSTRAINT uq_users_email UNIQUE (email),
    CONSTRAINT uq_users_customer UNIQUE (customer_id),
    CONSTRAINT fk_users_customer FOREIGN KEY (customer_id) REFERENCES customers (id)
);

CREATE SEQUENCE account_number_seq START WITH 10000001;

CREATE TABLE accounts (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agency          VARCHAR(10)    NOT NULL,
    number          VARCHAR(20)    NOT NULL,
    type            VARCHAR(20)    NOT NULL,
    status          VARCHAR(20)    NOT NULL,
    balance         NUMERIC(19, 2) NOT NULL DEFAULT 0,
    overdraft_limit NUMERIC(19, 2) NOT NULL DEFAULT 0,
    customer_id     BIGINT,
    version         BIGINT         NOT NULL DEFAULT 0,
    created_at      TIMESTAMPTZ    NOT NULL DEFAULT now(),
    CONSTRAINT uq_accounts_agency_number UNIQUE (agency, number),
    CONSTRAINT fk_accounts_customer FOREIGN KEY (customer_id) REFERENCES customers (id),
    CONSTRAINT ck_accounts_type CHECK (type IN ('CORRENTE', 'POUPANCA', 'CAIXA')),
    CONSTRAINT ck_accounts_status CHECK (status IN ('ATIVA', 'BLOQUEADA', 'ENCERRADA')),
    CONSTRAINT ck_accounts_overdraft CHECK (overdraft_limit >= 0),
    CONSTRAINT ck_accounts_savings_no_overdraft CHECK (type <> 'POUPANCA' OR overdraft_limit = 0),
    CONSTRAINT ck_accounts_owner CHECK (type = 'CAIXA' OR customer_id IS NOT NULL),
    CONSTRAINT ck_accounts_balance CHECK (type = 'CAIXA' OR balance >= -overdraft_limit)
);
CREATE INDEX ix_accounts_customer ON accounts (customer_id);

CREATE TABLE transactions (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type            VARCHAR(20)    NOT NULL,
    amount          NUMERIC(19, 2) NOT NULL,
    description     VARCHAR(140),
    initiated_by    BIGINT,
    idempotency_key VARCHAR(255),
    created_at      TIMESTAMPTZ    NOT NULL,
    CONSTRAINT ck_transactions_type CHECK (type IN ('DEPOSIT', 'WITHDRAWAL', 'TRANSFER', 'REVERSAL')),
    CONSTRAINT ck_transactions_amount CHECK (amount > 0),
    CONSTRAINT fk_transactions_initiator FOREIGN KEY (initiated_by) REFERENCES customers (id)
);

CREATE TABLE ledger_entries (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id BIGINT         NOT NULL,
    account_id     BIGINT         NOT NULL,
    direction      VARCHAR(6)     NOT NULL,
    amount         NUMERIC(19, 2) NOT NULL,
    balance_after  NUMERIC(19, 2) NOT NULL,
    created_at     TIMESTAMPTZ    NOT NULL,
    CONSTRAINT fk_ledger_transaction FOREIGN KEY (transaction_id) REFERENCES transactions (id),
    CONSTRAINT fk_ledger_account FOREIGN KEY (account_id) REFERENCES accounts (id),
    CONSTRAINT ck_ledger_direction CHECK (direction IN ('DEBIT', 'CREDIT')),
    CONSTRAINT ck_ledger_amount CHECK (amount > 0)
);
CREATE INDEX ix_ledger_account_created ON ledger_entries (account_id, created_at, id);
CREATE INDEX ix_ledger_transaction ON ledger_entries (transaction_id);

CREATE TABLE idempotency_keys (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id        BIGINT       NOT NULL,
    idem_key        VARCHAR(255) NOT NULL,
    request_hash    VARCHAR(64)  NOT NULL,
    status          VARCHAR(20)  NOT NULL,
    response_status INT,
    response_body   TEXT,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uq_idempotency_owner_key UNIQUE (owner_id, idem_key),
    CONSTRAINT ck_idempotency_status CHECK (status IN ('IN_PROGRESS', 'COMPLETED'))
);
CREATE INDEX ix_idempotency_created ON idempotency_keys (created_at);
